"""Phase 3a - alpha-lambda diagram and maintenance decision simulation, on CROSS-VALIDATION
predictions only (validation engines, full trajectories). The test set is not used here.

Decision rule: schedule maintenance at the first cycle where the bound (q05, or q50 for
comparison) of the predicted RUL is <= L. The part arrives / the job is done L cycles later.
  * failure   : no alert before failure, or true RUL at the alert < L (too late)
  * wasted    : true RUL at the alert - L (useful life thrown away), for successful interventions
"""
from __future__ import annotations

import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.data import ROOT  # noqa: E402
from src.frozen import CV_KEYS, LEAD_TIME, LEAD_TIMES  # noqa: E402
from src.metrics import alpha_lambda_hits  # noqa: E402

REPORT = ROOT / "reports"
FIG = REPORT / "figures"
ALPHA = 0.2
LAMBDAS = (0.25, 0.5, 0.75, 0.9)
COLORS = {"B0": "tab:gray", "B1": "tab:orange", "M1": "tab:green"}


def md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    out = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(str(v) for v in r.values) + " |" for _, r in df.iterrows()]
    return "\n".join(out)


def simulate(P: pd.DataFrame, bound: str, L: int) -> pd.DataFrame:
    rows = []
    for unit, u in P.groupby("unit"):
        u = u.sort_values("cycle")
        hit = u[u[bound] <= L]
        if hit.empty:
            rows.append({"unit": unit, "alert": False, "rul_at_alert": np.nan, "failure": True, "wasted": np.nan})
            continue
        r = float(hit["RUL"].iloc[0])
        fail = r < L
        rows.append({"unit": unit, "alert": True, "rul_at_alert": r, "failure": fail,
                     "wasted": np.nan if fail else r - L})
    return pd.DataFrame(rows)


def main() -> None:
    P = pd.read_csv(REPORT / "cv_predictions.csv.gz")
    P = P[P["config"].isin(CV_KEYS.values())].copy()
    inv = {v: k for k, v in CV_KEYS.items()}
    P["model"] = P["config"].map(inv)
    life = P.groupby("unit")["cycle"].transform("max")
    P["lam"] = P["cycle"] / life
    out = ["# Phase 3a - alpha-lambda and decision simulation (cross-validation predictions)", "",
           "_Generated by `python -m src.decision`. Validation engines of the 5 GroupKFold folds "
           "(each engine predicted by a model that never saw it), full trajectories. Test set not used._", ""]

    # ---- alpha-lambda accuracy at fixed lambdas
    rows = []
    for m in ("B0", "B1", "M1"):
        r = {"model": m}
        for lam in LAMBDAS:
            pts = P[P["model"] == m].assign(dl=lambda d: (d["lam"] - lam).abs())
            pts = pts.loc[pts.groupby("unit")["dl"].idxmin()]       # cycle closest to lambda, per unit
            r[f"λ={lam}"] = f"{alpha_lambda_hits(pts['RUL'], pts['q50'], ALPHA).mean():.0%}"
        rows.append(r)
    out += [f"## 1. α-λ accuracy (α = {ALPHA:.0%}): share of the 100 engines whose predicted RUL is within "
            f"±{ALPHA:.0%} of the true RUL at fraction λ of their life", "", md(pd.DataFrame(rows)), "",
            "Early in life (λ = 0.25, true RUL ≈ 150) a model capped at R_max can't be within ±20 % by "
            "construction: the α-λ criterion only becomes meaningful once degradation is observable. "
            "B1's 63 % at λ = 0.5 is an artefact: its fallback value R_max = 100 happens to be close to "
            "the true RUL at mid-life; at λ = 0.75-0.9, when its trend kicks in, it lags (late bias).", ""]

    # ---- alpha-lambda figure: predicted vs true RUL with the cone
    fig, axes = plt.subplots(1, 3, figsize=(14, 4), sharey=True)
    grid = np.arange(0, 201, 5)
    for ax, m in zip(axes, ("B0", "B1", "M1")):
        d = P[(P["model"] == m) & (P["RUL"] <= 200)].copy()
        d["b"] = (d["RUL"] // 5) * 5
        g = d.groupby("b")["q50"]
        ax.fill_between(grid, grid * (1 - ALPHA), grid * (1 + ALPHA), color="k", alpha=.08, label="±20 % cone")
        ax.plot(grid, grid, "k--", lw=.8, label="perfect")
        ax.fill_between(g.quantile(.1).index, g.quantile(.1), g.quantile(.9), color=COLORS[m], alpha=.25,
                        label="10-90 % of engines")
        ax.plot(g.median().index, g.median(), color=COLORS[m], lw=1.8, label="median prediction")
        ax.set_xlim(200, 0); ax.set_xlabel("true RUL (cycles) → failure"); ax.set_title(f"{m} ({CV_KEYS[m]})", fontsize=9)
    axes[0].set_ylabel("predicted RUL"); axes[0].legend(frameon=False, fontsize=7)
    fig.suptitle("α-λ diagram (cross-validation, 100 engines)", fontsize=10)
    fig.tight_layout(); fig.savefig(FIG / "20_alpha_lambda.png", dpi=150); plt.close(fig)

    # ---- decision simulation
    rows = []
    for m in ("B0", "B1", "M1"):
        for bound in ("q05", "q50"):
            for L in LEAD_TIMES:
                s = simulate(P[P["model"] == m], bound, L)
                rows.append({"model": m, "decision bound": bound, "L": L,
                             "failures /100": int(s["failure"].sum()),
                             "no alert": int((~s["alert"]).sum()),
                             "mean wasted cycles": round(float(s["wasted"].mean()), 1),
                             "median RUL at alert": round(float(s["rul_at_alert"].median()), 1)})
    D = pd.DataFrame(rows)
    D.to_csv(REPORT / "decision_cv.csv", index=False)
    main_tab = D[D["L"] == LEAD_TIME].drop(columns="L")
    out += [f"## 2. Decision rule at L = {LEAD_TIME} cycles", "",
            "Alert at the first cycle where the bound <= L; maintenance done L cycles later. "
            "*Failure* = the engine fails before the maintenance (or no alert at all). *Wasted* = useful "
            "life left at the maintenance, averaged over **successful** interventions only (100 − failures "
            "engines), so it is unreliable when failures are frequent.", "", md(main_tab), "",
            "## 3. Sensitivity to the lead time", "", md(D), ""]

    fig, ax = plt.subplots(figsize=(6.5, 4))
    for m in ("B0", "B1", "M1"):
        for bound, mk in (("q05", "o"), ("q50", "x")):
            d = D[(D["model"] == m) & (D["decision bound"] == bound)]
            ax.plot(d["mean wasted cycles"], d["failures /100"], marker=mk, color=COLORS[m],
                    label=f"{m} - {bound}", lw=1)
            for _, r in d.iterrows():
                ax.annotate(f"L={r['L']}", (r["mean wasted cycles"], r["failures /100"]), fontsize=6,
                            xytext=(3, 3), textcoords="offset points")
    ax.set_xlabel("mean wasted life per engine (cycles)"); ax.set_ylabel("failures per 100 engines")
    ax.set_title("Decision trade-off (CV): lower-left is better"); ax.legend(frameon=False, fontsize=7)
    fig.tight_layout(); fig.savefig(FIG / "21_decision_tradeoff.png", dpi=150); plt.close(fig)

    out += ["Figures: `reports/figures/20_alpha_lambda.png`, `21_decision_tradeoff.png`."]
    (REPORT / "decision_cv.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
