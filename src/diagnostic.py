"""Phase 1 - Diagnostic of the raw C-MAPSS FD001 data.

Produces reports/diagnostic.md (logged findings) and reports/figures/*.png.

Leakage policy for this phase:
  * Everything here is DESCRIPTIVE. No threshold, sensor list or scaler computed here is
    reused by a model: the final sensor selection / HI / scaling will be refitted inside
    each training fold (Phase 2).
  * The test set is only checked STRUCTURALLY (shape, grid, consistency with the RUL file).
    The test RUL labels are deliberately NOT analysed: they are used once, at the very end.
"""
from __future__ import annotations

import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy.stats import spearmanr

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.data import (  # noqa: E402
    DATA_DIR, ROOT, SENSORS, SETTINGS, add_train_rul, load_test, load_test_rul, load_train, sha256,
)

SUBSET = "FD001"
SEED = 42
REPORT_DIR = ROOT / "reports"
FIG_DIR = REPORT_DIR / "figures"
FLAT_STD = 1e-3          # std below which a channel is considered constant
HAMPEL_K, HAMPEL_W = 3.0, 21  # causal Hampel: 3 robust sigmas, window of 21 past points

lines: list[str] = []


def log(s: str = "") -> None:
    print(s)
    lines.append(s)


def md_table(df: pd.DataFrame, floatfmt: str = "{:.4g}") -> str:
    def fmt(v):
        if isinstance(v, (float, np.floating)):
            return floatfmt.format(v)
        return str(v)
    cols = [str(c) for c in df.columns]
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(fmt(v) for v in r.values) + " |")
    return "\n".join(out)


# --------------------------------------------------------------------------- 1. grid
def grid_checks(df: pd.DataFrame, name: str) -> dict:
    g = df.groupby("unit")["cycle"]
    steps = g.diff().dropna()
    res = {
        "file": name,
        "rows": len(df),
        "units": df["unit"].nunique(),
        "unit ids contiguous": bool((np.sort(df["unit"].unique()) == np.arange(1, df["unit"].nunique() + 1)).all()),
        "NaN cells": int(df.isna().sum().sum()),
        "non-numeric cols": int((~df.dtypes.apply(pd.api.types.is_numeric_dtype)).sum()),
        "exact dup rows": int(df.duplicated().sum()),
        "dup (unit,cycle)": int(df.duplicated(["unit", "cycle"]).sum()),
        "rows sorted": bool(df.sort_values(["unit", "cycle"]).index.equals(df.index)),
        "cycle starts at 1": bool((g.min() == 1).all()),
        "steps != 1": int((steps != 1).sum()),
        "missing cycles": int((steps[steps > 1] - 1).sum()),
    }
    return res


# --------------------------------------------------------------------------- 4. trend
def per_unit_spearman(df: pd.DataFrame, cols: list[str]) -> pd.DataFrame:
    rows = []
    for c in cols:
        rhos = []
        for _, u in df.groupby("unit"):
            if u[c].nunique() > 1:
                rhos.append(spearmanr(u["cycle"], u[c])[0])
        rhos = np.asarray(rhos)
        med = np.median(rhos)
        rows.append({
            "sensor": c,
            "median rho(cycle)": med,
            "IQR": np.subtract(*np.percentile(rhos, [75, 25])),
            "share same sign": float(np.mean(np.sign(rhos) == np.sign(med))),
        })
    return pd.DataFrame(rows).sort_values("median rho(cycle)", key=np.abs, ascending=False)


def monotonicity(df: pd.DataFrame, cols: list[str], w: int = 10) -> pd.Series:
    """Mon = |#(d>0) - #(d<0)| / (n-1) on a CAUSAL rolling mean (trailing window), averaged over units."""
    out = {}
    for c in cols:
        vals = []
        for _, u in df.groupby("unit"):
            sm = u[c].rolling(w, min_periods=w).mean().dropna()   # trailing window: causal
            d = np.diff(sm.values)
            if len(d):
                vals.append(abs((d > 0).sum() - (d < 0).sum()) / len(d))
        out[c] = float(np.mean(vals))
    return pd.Series(out, name="monotonicity")


def causal_hampel_flags(x: pd.Series) -> pd.Series:
    """Flag x(t) against median/MAD of the W PREVIOUS points only (shift(1) before rolling)."""
    past = x.shift(1).rolling(HAMPEL_W, min_periods=HAMPEL_W)
    med = past.median()
    mad = x.shift(1).rolling(HAMPEL_W, min_periods=HAMPEL_W).apply(
        lambda v: np.median(np.abs(v - np.median(v))), raw=True)
    sigma = 1.4826 * mad
    return (np.abs(x - med) > HAMPEL_K * sigma) & (sigma > 0)


# --------------------------------------------------------------------------- main
def main() -> None:
    np.random.seed(SEED)
    FIG_DIR.mkdir(parents=True, exist_ok=True)

    log(f"# Phase 1 - Diagnostic of C-MAPSS {SUBSET}")
    log()
    log("_Generated by `python -m src.diagnostic`. Descriptive only: nothing computed here is "
        "reused by a model; test labels are not analysed._")
    log()

    # ---- 0. provenance
    log("## 0. Provenance of the raw data")
    log()
    log("Source: NASA C-MAPSS (Saxena et al., PHM08), "
        "https://data.nasa.gov/dataset/c-mapss-aircraft-engine-simulator-data")
    log()
    prov = pd.DataFrame([{"file": f, "sha256 (first 16)": sha256(DATA_DIR / f)[:16]}
                         for f in [f"train_{SUBSET}.txt", f"test_{SUBSET}.txt", f"RUL_{SUBSET}.txt"]])
    log(md_table(prov))
    log()

    train = load_train(SUBSET)
    test = load_test(SUBSET)
    rul_test = load_test_rul(SUBSET)

    # ---- 1. grid
    log("## 1. Temporal grid, duplicates, missing values")
    log()
    log("Checks, in the course order: duplicates -> ordering -> gaps -> completeness.")
    log()
    grid = pd.DataFrame([grid_checks(train, "train"), grid_checks(test, "test")]).set_index("file").T
    grid = grid.reset_index().rename(columns={"index": "check"})
    log(md_table(grid))
    log()
    lab_ok = len(rul_test) == test["unit"].nunique() and bool((rul_test > 0).all()) \
        and pd.api.types.is_integer_dtype(rul_test)
    log(f"- `RUL_{SUBSET}.txt`: {len(rul_test)} values, one per test unit, positive integers: "
        f"**{'OK' if lab_ok else 'PROBLEM'}** (values not inspected).")
    tr_complete = 1 - grid_checks(train, "t")["missing cycles"] / len(train)
    log(f"- Completeness of the cycle grid (train): {tr_complete:.1%}.")
    log("- **Missingness mechanism:** no cell is missing. The only 'missing' information is the "
        "end of each test trajectory, which is **right-censored by design** (the series stops "
        "before failure). This is not MCAR noise: it fixes the task (predict RUL from a partial "
        "history) and the validation must reproduce it (truncate validation units).")
    log()

    # ---- 2. orders of magnitude
    log("## 2. Orders of magnitude and constant channels")
    log()
    cols = SETTINGS + SENSORS
    desc = pd.DataFrame({
        "channel": cols,
        "mean": train[cols].mean().values,
        "std": train[cols].std().values,
        "min": train[cols].min().values,
        "max": train[cols].max().values,
        "n unique": train[cols].nunique().values,
    })
    desc["cv"] = desc["std"] / desc["mean"].abs().replace(0, np.nan)
    # NB: no coefficient-of-variation rule: s8/s13 sit near 2388 with tiny CV but do move.
    desc["flat"] = (desc["std"] < FLAT_STD) | (desc["n unique"] <= 2)
    log(md_table(desc))
    log()
    flat_sensors = [c for c in desc.loc[desc["flat"], "channel"] if c in SENSORS]
    informative = [s for s in SENSORS if s not in flat_sensors]
    log(f"- Constant / quasi-constant sensors (std < {FLAT_STD} or <= 2 distinct values): "
        f"**{', '.join(flat_sensors)}** -> carry no degradation information.")
    log(f"- Remaining candidate sensors ({len(informative)}): {', '.join(informative)}.")
    os_std = train[SETTINGS].std()
    log("- Operating settings std: " + ", ".join(f"{k}={v:.2g}" for k, v in os_std.items())
        + " -> a **single operating regime** (sea level), as stated in the readme. "
          "No per-regime normalisation is needed for FD001.")
    log()

    # ---- 3. lifetimes and censoring
    log("## 3. Lifetimes (train) and history lengths (test)")
    log()
    life = train.groupby("unit")["cycle"].max()
    hist = test.groupby("unit")["cycle"].max()
    lt = pd.DataFrame({
        "quantity": ["train lifetime (cycles)", "test observed history (cycles)"],
        "min": [life.min(), hist.min()], "q25": [life.quantile(.25), hist.quantile(.25)],
        "median": [life.median(), hist.median()], "mean": [life.mean(), hist.mean()],
        "q75": [life.quantile(.75), hist.quantile(.75)], "max": [life.max(), hist.max()],
    })
    log(md_table(lt, "{:.1f}"))
    log()
    short = int((hist < 50).sum())
    log(f"- {short} test units have fewer than 50 observed cycles: features must work with short "
        "histories (windows with `min_periods`, or an expanding fallback).")
    log(f"- Train lifetime spread (CV = {life.std() / life.mean():.2f}) shows large unit-to-unit "
        "variability (different initial wear / manufacturing): a population-average lifetime "
        "will be a weak predictor, the trend of each unit must be used.")
    log("- Test histories are shorter than train lifetimes by construction: evaluating on full "
        "train trajectories (mostly near failure) would be over-optimistic -> validation units "
        "will be **truncated at random cut points** to mimic the test.")
    log()

    # ---- 4. trends
    log("## 4. Sensor trends with cycle (per unit)")
    log()
    log("Spearman rho between each sensor and cycle, computed **unit by unit** (pooling units "
        "would mix inter-unit offsets with degradation), then summarised across the 100 units. "
        "Monotonicity uses a trailing (causal) 10-cycle mean.")
    log()
    sp = per_unit_spearman(train, informative)
    mon = monotonicity(train, informative)
    sp["monotonicity"] = sp["sensor"].map(mon)
    log(md_table(sp, "{:.3f}"))
    log()
    strong = sp.loc[(sp["median rho(cycle)"].abs() >= 0.5) & (sp["share same sign"] >= 0.9), "sensor"].tolist()
    weak = [s for s in informative if s not in strong]
    log(f"- Clear monotone trend (|median rho| >= 0.5 and same sign in >= 90% of units): "
        f"**{', '.join(strong)}**.")
    log(f"- Weak / inconsistent trend: {', '.join(weak) if weak else 'none'}.")
    inc = sp.loc[sp["sensor"].isin(strong) & (sp["median rho(cycle)"] > 0), "sensor"].tolist()
    dec = sp.loc[sp["sensor"].isin(strong) & (sp["median rho(cycle)"] < 0), "sensor"].tolist()
    log(f"- Increasing with wear: {', '.join(inc)}; decreasing: {', '.join(dec)} "
        "(signs must be aligned before combining into a health indicator).")
    log("- This list is a **hypothesis**; the selection actually used by the models is re-done "
        "inside each training fold (Phase 2).")
    log()

    # ---- 5. noise and outliers
    log("## 5. Noise level and outliers")
    log()
    rng = np.random.default_rng(SEED)
    g = pd.Series(rng.normal(size=20000))
    gauss_rate = causal_hampel_flags(g).sum() / g.shift(1).rolling(HAMPEL_W).count().notna().sum()
    rows = []
    for s in informative:
        sig_ratio, flags, n = [], 0, 0
        for _, u in train.groupby("unit"):
            x = u[s].reset_index(drop=True)
            trend = x.rolling(20, min_periods=20).mean()          # trailing
            resid = (x - trend).dropna()
            amp = trend.dropna().iloc[-1] - trend.dropna().iloc[0] if trend.notna().sum() > 1 else 0
            if resid.std() > 0:
                sig_ratio.append(abs(amp) / resid.std())
            # Hampel on the causally detrended signal (slow wear is not an outlier)
            r = (x - x.shift(1).rolling(20, min_periods=5).mean()).dropna().reset_index(drop=True)
            flags += int(causal_hampel_flags(r).sum())
            n += int(r.shift(1).rolling(HAMPEL_W).count().notna().sum())
        rows.append({"sensor": s, "drift / noise (median)": np.median(sig_ratio) if sig_ratio else np.nan,
                     "n distinct": train[s].nunique(), "Hampel flag rate": flags / n})
    noise = pd.DataFrame(rows).sort_values("drift / noise (median)", ascending=False)
    log(md_table(noise, "{:.3g}"))
    log()
    log(f"- Causal Hampel filter ({HAMPEL_K:g} robust sigmas, median/MAD of the {HAMPEL_W} previous "
        f"cycles, applied to the causally detrended signal). **Reference: the same filter flags "
        f"{gauss_rate:.1%} of pure Gaussian white noise** (short windows make MAD noisy). Sensor flag "
        "rates match this reference: no evidence of gross errors, spikes or saturation. Points would "
        "be **flagged, not removed** (a spike can be an early degradation sign).")
    q = noise.loc[noise["n distinct"] < 30, "sensor"].tolist()
    if q:
        log(f"- {', '.join(q)} is coarsely quantised (integer steps, a handful of distinct values): its "
            "MAD is often 0 or 1 step, so its Hampel rate is inflated by quantisation, not by outliers. "
            "Quantisation also limits how early it can reveal degradation.")
    log("- Drift-over-life is only a few times the cycle-to-cycle noise: a single cycle is not "
        "informative, **trailing smoothing / regression over a window** is needed. Smoothing must be "
        "causal (trailing mean, EWM, Kalman) - never centred windows, filtfilt or Savitzky-Golay.")
    log()

    # ---- 6. hypotheses for the baseline
    log("## 6. Consequences for the next phases")
    log()
    log("1. Drop the constant channels; work with the trending sensors (re-selected per fold).")
    log("2. No imputation / deduplication needed (clean grid) - the preparation log will still "
        "record row counts at each step.")
    log("3. Group = unit: GroupKFold by unit; all fitted objects (selection, HI weights, scaler, "
        "failure threshold) fitted on training units only.")
    log("4. Validation units truncated at random cut points to reproduce test censoring.")
    log("5. Early life shows no visible trend (see figures): motivates a capped RUL target for the "
        "direct regression (P-F curve argument).")
    log()
    log("Figures: `reports/figures/`.")

    # ---- figures
    make_figures(train, life, hist, sp, strong)

    (REPORT_DIR / "diagnostic.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\nWritten {REPORT_DIR / 'diagnostic.md'}")


def make_figures(train, life, hist, sp, strong) -> None:
    rng = np.random.default_rng(SEED)
    tr = add_train_rul(train)

    # lifetimes vs test history lengths
    fig, ax = plt.subplots(figsize=(7, 3.5))
    bins = np.arange(0, 380, 15)
    ax.hist(life, bins=bins, alpha=.7, label="train: full lifetime")
    ax.hist(hist, bins=bins, alpha=.7, label="test: observed history (censored)")
    ax.set_xlabel("cycles"); ax.set_ylabel("units"); ax.legend(frameon=False)
    ax.set_title("FD001 - lifetimes vs censored test histories")
    fig.tight_layout(); fig.savefig(FIG_DIR / "01_lifetimes.png", dpi=150); plt.close(fig)

    # trending sensors vs RUL for a sample of units
    units = rng.choice(tr["unit"].unique(), size=10, replace=False)
    n = len(strong); ncol = 4; nrow = int(np.ceil(n / ncol))
    fig, axes = plt.subplots(nrow, ncol, figsize=(13, 2.6 * nrow), squeeze=False)
    for ax, s in zip(axes.flat, strong):
        for u in units:
            d = tr[tr["unit"] == u]
            ax.plot(-d["RUL"], d[s], lw=.7, alpha=.8)
        ax.set_title(s, fontsize=9); ax.set_xlabel("- RUL (cycles before failure)", fontsize=8)
        ax.tick_params(labelsize=7)
    for ax in list(axes.flat)[n:]:
        ax.axis("off")
    fig.suptitle("Trending sensors, 10 random training units, aligned on failure", fontsize=10)
    fig.tight_layout(); fig.savefig(FIG_DIR / "02_sensors_vs_rul.png", dpi=150); plt.close(fig)

    # per-unit spearman summary
    fig, ax = plt.subplots(figsize=(7, 3.5))
    spp = sp.sort_values("median rho(cycle)")
    colors = ["tab:blue" if s in strong else "lightgray" for s in spp["sensor"]]
    ax.barh(spp["sensor"], spp["median rho(cycle)"], color=colors)
    ax.axvline(0, color="k", lw=.6)
    ax.set_xlabel("median per-unit Spearman rho(sensor, cycle)")
    ax.set_title("Monotone trend per sensor (blue = retained hypothesis)")
    fig.tight_layout(); fig.savefig(FIG_DIR / "03_trend_strength.png", dpi=150); plt.close(fig)

    # one unit, raw vs trailing mean (noise vs drift)
    u = tr[tr["unit"] == units[0]]
    fig, axes = plt.subplots(1, 3, figsize=(12, 3))
    for ax, s in zip(axes, strong[:3]):
        ax.plot(u["cycle"], u[s], lw=.6, color="gray", label="raw")
        ax.plot(u["cycle"], u[s].rolling(15, min_periods=1).mean(), lw=1.5, label="trailing mean (15)")
        ax.set_title(f"unit {units[0]} - {s}", fontsize=9); ax.set_xlabel("cycle")
    axes[0].legend(frameon=False, fontsize=8)
    fig.tight_layout(); fig.savefig(FIG_DIR / "04_noise_vs_drift.png", dpi=150); plt.close(fig)


if __name__ == "__main__":
    main()
